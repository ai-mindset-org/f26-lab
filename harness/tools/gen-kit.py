def md_html(t):
    t = t.replace('{{name}}', ANSWERS['default']['name'])
    out, lines, i = [], t.split('\n'), 0
    def inl(x):
        x = H.escape(x)
        x = RE.sub(r'`([^`]+)`', r'<code>\1</code>', x)
        x = RE.sub(r'\*\*([^*]+)\*\*', r'<b>\1</b>', x)
        return RE.sub(r'\[\[([^\]|]+)\]\]', lambda m: '<code>' + RE.sub(r' – \d{4}-\d{2}-\d{2}$', '', m.group(1)) + '</code>', x)
    while i < len(lines):
        l = lines[i]
        if not l.strip(): i += 1; continue
        if l.startswith('|'):
            rows = []
            while i < len(lines) and lines[i].startswith('|'): rows.append(lines[i]); i += 1
            cells = [[c.strip() for c in r.strip('|').split('|')] for r in rows if not RE.match(r'^\|[-| ]+\|$', r)]
            out.append('<table class="t"><tr>' + ''.join(f'<th>{inl(c)}</th>' for c in cells[0]) + '</tr>' + ''.join('<tr>' + ''.join(f'<td>{inl(c)}</td>' for c in r) + '</tr>' for r in cells[1:]) + '</table>'); continue
        m = RE.match(r'^(\d+)\. (.*)', l)
        if m or l.startswith('- '):
            tag = 'ol' if m else 'ul'; items = []
            while i < len(lines) and (RE.match(r'^\d+\. ', lines[i]) if tag == 'ol' else lines[i].startswith('- ')):
                items.append(RE.sub(r'^(\d+\. |- )', '', lines[i])); i += 1
            out.append(f'<{tag} class="steps">' + ''.join(f'<li>{inl(x)}</li>' for x in items) + f'</{tag}>'); continue
        out.append(f'<p>{inl(l)}</p>'); i += 1
    return '\n'.join(out)
def inject(path, mark, body):
    t = path.read_text(); a, b = f'<!-- {mark}:start -->', f'<!-- {mark}:end -->'
